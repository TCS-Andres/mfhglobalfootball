export type UIKey = keyof (typeof ui)['en'];

/** Returns the string for a locale, falling back to the key if missing. */
export function t(lang: Lang, key: string): string {
  const dict = ui[lang] as Record<string, string>;
  const fallback = ui[defaultLang] as Record<string, string>;
  return dict[key] ?? fallback[key] ?? key;
}

const localeCodes = Object.keys(languages) as Lang[];
const prefixPattern = new RegExp(`^/(${localeCodes.filter((l) => l !== defaultLang).join('|')})(?=/|$)`);

/**
 * Build a locale aware href from a canonical English path.
 * English serves with no prefix, every other locale under /<code>/.
 */
export function localizePath(path: string, lang: Lang): string {
  const clean = '/' + path.replace(/^\/+/, '');
  if (lang === defaultLang) return clean;
  if (clean === '/') return `/${lang}/`;
  return `/${lang}` + clean;
}

/** Read the active locale from an Astro URL pathname. */
export function getLangFromPath(pathname: string): Lang {
  const m = pathname.match(prefixPattern);
  return (m ? m[1] : defaultLang) as Lang;
}

/** Given the current pathname, return the equivalent path in every locale. */
export function localePaths(pathname: string): Record<Lang, string> {
  let canonical = pathname.replace(prefixPattern, '') || '/';
  if (!canonical.startsWith('/')) canonical = '/' + canonical;
  return Object.fromEntries(
    localeCodes.map((l) => [l, localizePath(canonical, l)])
  ) as Record<Lang, string>;
}
